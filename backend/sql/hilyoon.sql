-- VIEWS FOR ANALYTICS AND REPORTING
-- =====================================================

-- Blog posts with category and author info
CREATE VIEW blog_posts_full AS
SELECT 
    p.*,
    c.name as category_name,
    c.slug as category_slug,
    c.color as category_color
FROM blog_posts p
JOIN blog_categories c ON p.category_id = c.id;

-- Analytics summary view
CREATE VIEW analytics_summary AS
SELECT 
    DATE(created_at) as date,
    COUNT(*) as total_views,
    COUNT(DISTINCT session_id) as unique_sessions,
    COUNT(DISTINCT ip_address) as unique_visitors,
    AVG(view_duration) as avg_duration
FROM page_views
WHERE created_at >= DATE_SUB(NOW(), INTERVAL 30 DAY)
GROUP BY DATE(created_at)
ORDER BY date DESC;

-- AI generation statistics view
CREATE VIEW ai_generation_stats AS
SELECT 
    DATE(created_at) as generation_date,
    type,
    status,
    COUNT(*) as count,
    AVG(tokens_used) as avg_tokens,
    SUM(tokens_used) as total_tokens,
    SUM(cost_usd) as total_cost
FROM ai_generation_log 
WHERE created_at >= DATE_SUB(NOW(), INTERVAL 30 DAY)
GROUP BY DATE(created_at), type, status
ORDER BY generation_date DESC, type;

-- Blog automation overview
CREATE VIEW blog_automation_overview AS
SELECT 
    bp.language,
    COUNT(*) as total_posts,
    COUNT(CASE WHEN bp.ai_generated = 1 THEN 1 END) as ai_generated_posts,
    COUNT(CASE WHEN bp.is_published = 1 THEN 1 END) as published_posts,
    AVG(bp.views_count) as avg_views,
    MAX(bp.published_at) as last_published,
    c.name as category_name
FROM blog_posts bp
LEFT JOIN blog_categories c ON bp.category_id = c.id
WHERE bp.created_at >= DATE_SUB(NOW(), INTERVAL 30 DAY)
GROUP BY bp.language, c.name
ORDER BY total_posts DESC;

