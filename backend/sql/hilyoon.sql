-- AI GENERATION LOG TABLE
CREATE TABLE ai_generation_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    type VARCHAR(50) NOT NULL COMMENT 'Type: rss_analysis, blog_post, blog_image, etc.',
    prompt TEXT COMMENT 'The prompt sent to AI',
    response LONGTEXT COMMENT 'AI response or result',
    status ENUM('success', 'failed', 'partial') NOT NULL,
    tokens_used INT DEFAULT 0 COMMENT 'OpenAI tokens consumed',
    cost_usd DECIMAL(10, 4) DEFAULT 0.0000 COMMENT 'Estimated cost in USD',
    error_message TEXT COMMENT 'Error message if failed',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    INDEX idx_type_status (type, status),
    INDEX idx_created_at (created_at),
    INDEX idx_tokens (tokens_used),
    CONSTRAINT chk_tokens_positive CHECK (tokens_used >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- AI USED TOPICS TABLE (Prevent duplicates)
CREATE TABLE ai_used_topics (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    title VARCHAR(500) NOT NULL,
    source VARCHAR(100) NOT NULL COMMENT 'RSS source: Microsoft, Fast.ai, NVIDIA',
    link VARCHAR(1000) NOT NULL,
    keywords TEXT COMMENT 'Comma-separated keywords',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    INDEX idx_title (title(100)),
    INDEX idx_source (source),
    INDEX idx_created_at (created_at),
    UNIQUE KEY unique_source_link (source, link(500))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- AUTOMATION SCHEDULE TABLE
CREATE TABLE automation_schedule (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_name VARCHAR(100) NOT NULL UNIQUE,
    interval_hours INT NOT NULL DEFAULT 6,
    last_run_time TIMESTAMP NULL,
    next_run_time TIMESTAMP NULL,
    is_active BOOLEAN DEFAULT TRUE,
    total_runs INT DEFAULT 0,
    success_runs INT DEFAULT 0,
    failed_runs INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    INDEX idx_job_name (job_name),
    INDEX idx_next_run (next_run_time),
    INDEX idx_active (is_active),
    CONSTRAINT chk_interval_positive CHECK (interval_hours > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- AUTOMATION EXECUTION LOG TABLE
CREATE TABLE automation_execution_log (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    job_name VARCHAR(100) NOT NULL,
    execution_id VARCHAR(100) NOT NULL,
    status ENUM('success', 'failed', 'error', 'no_content') NOT NULL,
    results LONGTEXT COMMENT 'JSON results of execution',
    execution_time DECIMAL(10,2) COMMENT 'Execution time in seconds',
    error_message TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    INDEX idx_job_name (job_name),
    INDEX idx_execution_id (execution_id),
    INDEX idx_status (status),
    INDEX idx_created_at (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

