DELIMITER $$

-- Get popular posts by views
CREATE PROCEDURE GetPopularPosts(IN language_param VARCHAR(5), IN limit_param INT)
BEGIN
    SELECT p.*, c.name as category_name, c.color as category_color
    FROM blog_posts p
    JOIN blog_categories c ON p.category_id = c.id
    WHERE p.is_published = 1 
    AND p.language = language_param
    ORDER BY p.views_count DESC, p.published_at DESC
    LIMIT limit_param;
END$$

-- Get recent posts
CREATE PROCEDURE GetRecentPosts(IN language_param VARCHAR(5), IN limit_param INT)
BEGIN
    SELECT p.*, c.name as category_name, c.color as category_color
    FROM blog_posts p
    JOIN blog_categories c ON p.category_id = c.id
    WHERE p.is_published = 1 
    AND p.language = language_param
    ORDER BY p.published_at DESC
    LIMIT limit_param;
END$$

-- Get featured posts
CREATE PROCEDURE GetFeaturedPosts(IN language_param VARCHAR(5), IN limit_param INT)
BEGIN
    SELECT p.*, c.name as category_name, c.color as category_color
    FROM blog_posts p
    JOIN blog_categories c ON p.category_id = c.id
    WHERE p.is_published = 1 
    AND p.is_featured = 1
    AND p.language = language_param
    ORDER BY p.published_at DESC
    LIMIT limit_param;
END$$

