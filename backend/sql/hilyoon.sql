-- =====================================================
-- CORE PLATFORM TABLES
-- =====================================================

-- USERS TABLE - Authentication and User Management
CREATE TABLE users (
    id INT PRIMARY KEY AUTO_INCREMENT,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    role ENUM('admin', 'editor', 'viewer') DEFAULT 'viewer',
    avatar VARCHAR(500) NULL,
    bio TEXT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    email_verified_at TIMESTAMP NULL,
    remember_token VARCHAR(100) NULL,
    last_login_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    INDEX idx_email (email),
    INDEX idx_role (role),
    INDEX idx_active (is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- BLOG CATEGORIES TABLE
CREATE TABLE blog_categories (
    id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    description TEXT NULL,
    color VARCHAR(20) DEFAULT '#3B82F6',
    language ENUM('en', 'ro', 'ar') DEFAULT 'en',
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    UNIQUE KEY unique_slug_language (slug, language),
    INDEX idx_slug (slug),
    INDEX idx_language (language),
    INDEX idx_active (is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- BLOG POSTS TABLE (Enhanced with AI features)
CREATE TABLE blog_posts (
    id INT PRIMARY KEY AUTO_INCREMENT,
    title VARCHAR(500) NOT NULL,
    slug VARCHAR(500) NOT NULL,
    excerpt TEXT NULL,
    content LONGTEXT NOT NULL,
    meta_title VARCHAR(500) NULL,
    meta_description TEXT NULL,
    meta_keywords TEXT NULL,
    featured_image VARCHAR(500) NULL,
    author_name VARCHAR(255) NOT NULL DEFAULT 'Hily Teco',
    author_email VARCHAR(255) NOT NULL DEFAULT 'hily.teco@hilyoon.com',
    category_id INT NOT NULL,
    tags TEXT NULL COMMENT 'Comma-separated tags',
    language ENUM('en', 'ro', 'ar') DEFAULT 'en',
    is_published BOOLEAN DEFAULT FALSE,
    is_featured BOOLEAN DEFAULT FALSE,
    read_time INT DEFAULT 0 COMMENT 'Estimated reading time in minutes',
    views_count INT DEFAULT 0,
    published_at TIMESTAMP NULL,
    
    -- AI Generation fields
    ai_generated BOOLEAN DEFAULT FALSE COMMENT 'Generated by AI',
    source_title VARCHAR(500) NULL COMMENT 'Original RSS title',
    source_link VARCHAR(1000) NULL COMMENT 'Original RSS link', 
    source_name VARCHAR(100) NULL COMMENT 'RSS source name',
    generation_prompt TEXT NULL COMMENT 'AI prompt used',
    
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    FOREIGN KEY (category_id) REFERENCES blog_categories(id) ON DELETE CASCADE,
    
    UNIQUE KEY unique_slug_language (slug, language),
    INDEX idx_slug (slug),
    INDEX idx_language (language),
    INDEX idx_published (is_published, published_at),
    INDEX idx_featured (is_featured),
    INDEX idx_views (views_count),
    INDEX idx_ai_generated (ai_generated),
    INDEX idx_source_name (source_name),
    FULLTEXT idx_search (title, excerpt, content, tags)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- BLOG TAGS TABLE
CREATE TABLE blog_tags (
    id INT PRIMARY KEY AUTO_INCREMENT,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL,
    language ENUM('en', 'ro', 'ar') DEFAULT 'en',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    UNIQUE KEY unique_tag_language (slug, language),
    INDEX idx_slug (slug),
    INDEX idx_language (language)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- BLOG POST TAGS RELATIONSHIP TABLE
CREATE TABLE blog_post_tags (
    post_id INT NOT NULL,
    tag_id INT NOT NULL,
    
    PRIMARY KEY (post_id, tag_id),
    FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE CASCADE,
    FOREIGN KEY (tag_id) REFERENCES blog_tags(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- PAGE VIEWS ANALYTICS TABLE
CREATE TABLE page_views (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    url VARCHAR(500) NOT NULL,
    post_id INT NULL,
    user_agent TEXT NULL,
    ip_address VARCHAR(45) NULL,
    referrer VARCHAR(500) NULL,
    country VARCHAR(100) NULL,
    device_type ENUM('desktop', 'mobile', 'tablet') NULL,
    session_id VARCHAR(255) NULL,
    view_duration INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    
    FOREIGN KEY (post_id) REFERENCES blog_posts(id) ON DELETE SET NULL,
    
    INDEX idx_url (url),
    INDEX idx_post (post_id),
    INDEX idx_date (created_at),
    INDEX idx_session (session_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- SYSTEM SETTINGS TABLE
CREATE TABLE system_settings (
    id INT PRIMARY KEY AUTO_INCREMENT,
    setting_key VARCHAR(255) UNIQUE NOT NULL,
    setting_value LONGTEXT NULL,
    description TEXT NULL,
    type ENUM('string', 'number', 'boolean', 'json', 'text') DEFAULT 'string',
    is_public BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    
    INDEX idx_key (setting_key),
    INDEX idx_public (is_public)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =====================================================
-- AI BLOG AUTOMATION TABLES
